export function resolveLocale(value) {
  if (value === 'es') return 'es'
  return 'en'
}

export function documentLocaleFromSource(sourceLanguage) {
  if (!sourceLanguage) return null
  const code = String(sourceLanguage).trim().toLowerCase().slice(0, 2)
  if (code === 'es') return 'es'
  if (code === 'en') return 'en'
  return null
}
